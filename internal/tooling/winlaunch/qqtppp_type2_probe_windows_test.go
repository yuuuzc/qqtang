package winlaunch

import (
	"bytes"
	"encoding/binary"
	"testing"
)

func TestBuildQQTPPPType2ProbeStubUsesOriginalThiscallArgumentOrder(t *testing.T) {
	stub := buildQQTPPPType2ProbeStub(0x11111111, 0x22222222, 0x33333333, 0x44, 0x55555555, 0x66666666, 0x77777777, 0x78787878, 0x88888888)
	wantPrefix := []byte{
		0x9C, 0x60, 0x6A, 0x01,
		0x68, 0x66, 0x66, 0x66, 0x66,
		0x68, 0x55, 0x55, 0x55, 0x55,
		0x68, 0x44, 0x00, 0x00, 0x00,
		0x68, 0x33, 0x33, 0x33, 0x33,
		0xB9, 0x22, 0x22, 0x22, 0x22,
		0xB8, 0x11, 0x11, 0x11, 0x11,
		0xFF, 0xD0, 0xA3, 0x77, 0x77, 0x77, 0x77,
	}
	if !bytes.HasPrefix(stub, wantPrefix) {
		t.Fatalf("stub prefix = %x, want %x", stub[:len(wantPrefix)], wantPrefix)
	}
	if got := binary.LittleEndian.Uint32(stub[len(stub)-5 : len(stub)-1]); got != 0x88888888 || stub[len(stub)-1] != 0xC3 {
		t.Fatalf("stub tail = %x", stub[len(stub)-5:])
	}
}
